// Chat Widget Controller
class ChatWidget {
  constructor() {
    this.container = document.getElementById('chat-widget-container');
    this.trigger = document.getElementById('chat-widget-trigger');
    this.closeBtn = document.getElementById('chat-close-btn');
    this.form = document.getElementById('chat-input-form');
    this.input = document.getElementById('chat-message-input');
    this.messagesArea = document.getElementById('chat-messages-area');
    
    this.socket = null;
    this.signedUrl = null;
    this.isConnecting = false;
    this.typingIndicator = null;

    this.initEvents();
  }

  initEvents() {
    // Open/Close Widget
    this.trigger.addEventListener('click', () => this.toggleWidget());
    this.closeBtn.addEventListener('click', () => this.closeWidget());

    // Send message on form submit
    this.form.addEventListener('submit', (e) => {
      e.preventDefault();
      this.handleSendMessage();
    });
  }

  toggleWidget() {
    const isActive = this.container.classList.toggle('active');
    this.trigger.classList.toggle('active');

    if (isActive) {
      this.input.focus();
      // Establish WebSocket connection once the widget opens
      this.connectWebSocket();
    }
  }

  closeWidget() {
    this.container.classList.remove('active');
    this.trigger.classList.remove('active');
  }

  // Connects to ElevenLabs using the signed URL generated by our backend
  async connectWebSocket() {
    if (this.socket && this.socket.readyState === WebSocket.OPEN) return;
    if (this.isConnecting) return;

    this.isConnecting = true;
    console.log('[Chat] Requesting signed URL from server...');

    try {
      // 1. Fetch the secure, temporary signed URL from our backend
      const response = await fetch('/api/signed-url');
      if (!response.ok) throw new Error('Failed to fetch signed URL');
      const data = await response.json();
      
      this.signedUrl = data.signedUrl;
      console.log('[Chat] Signed URL generated. Opening WebSocket connection...');

      // 2. Open WebSocket connection directly to ElevenLabs
      this.socket = new WebSocket(this.signedUrl);

      this.socket.onopen = () => {
        console.log('[Chat] WebSocket connection established successfully.');
        this.isConnecting = false;
        
        // Suppress initial greeting override if needed
        const initMsg = {
          type: "conversation_initiation_client_data",
          conversation_config_override: {
            agent: {
              first_message: "" // Let the text conversation start dynamically
            }
          }
        };
        this.socket.send(JSON.stringify(initMsg));
      };

      this.socket.onmessage = (event) => {
        try {
          const parsed = JSON.parse(event.data);
          
          // Check if it's the agent response text event
          if (parsed.type === 'agent_response' && parsed.agent_response_event) {
            const agentReply = parsed.agent_response_event.agent_response;
            this.removeTypingIndicator();
            this.appendMessage(agentReply, 'incoming');
          }
        } catch (err) {
          // Silent catch for binary voice chunks or ping messages in the protocol
        }
      };

      this.socket.onerror = (error) => {
        console.error('[Chat] WebSocket error:', error);
        this.isConnecting = false;
      };

      this.socket.onclose = () => {
        console.log('[Chat] WebSocket connection closed.');
        this.isConnecting = false;
        this.socket = null;
      };

    } catch (err) {
      console.error('[Chat] Failed to connect:', err.message);
      this.isConnecting = false;
      this.appendMessage("Unable to connect to assistant. Please refresh the page.", 'incoming');
    }
  }

  handleSendMessage() {
    const text = this.input.value.trim();
    if (!text) return;

    // Append user message bubble to chat window
    this.appendMessage(text, 'outgoing');
    this.input.value = '';

    // Show typing bubble to signify the AI is thinking
    this.showTypingIndicator();

    // Check if socket is open and ready to transmit
    if (this.socket && this.socket.readyState === WebSocket.OPEN) {
      const messagePayload = {
        type: 'user_message',
        user_message: text
      };
      
      this.socket.send(JSON.stringify(messagePayload));
    } else {
      console.warn('[Chat] Socket not open. Attempting to reconnect and send...');
      // Fallback: Re-connect and display connection failure helper
      this.connectWebSocket().then(() => {
        if (this.socket && this.socket.readyState === WebSocket.OPEN) {
          this.socket.send(JSON.stringify({
            type: 'user_message',
            user_message: text
          }));
        } else {
          this.removeTypingIndicator();
          this.appendMessage("Message couldn't be sent. Connection offline.", 'incoming');
        }
      });
    }
  }

  appendMessage(text, direction) {
    const messageDiv = document.createElement('div');
    messageDiv.className = `message ${direction}`;

    const bubble = document.createElement('div');
    bubble.className = 'message-bubble';
    bubble.innerText = text;

    const timeSpan = document.createElement('span');
    timeSpan.className = 'message-time';
    const now = new Date();
    timeSpan.innerText = now.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });

    messageDiv.appendChild(bubble);
    messageDiv.appendChild(timeSpan);
    
    this.messagesArea.appendChild(messageDiv);
    this.scrollToBottom();
  }

  showTypingIndicator() {
    if (this.typingIndicator) return;

    const indicatorDiv = document.createElement('div');
    indicatorDiv.className = 'message incoming typing-message';
    
    const bubble = document.createElement('div');
    bubble.className = 'message-bubble';
    
    const typingContainer = document.createElement('div');
    typingContainer.className = 'typing-indicator';
    
    for (let i = 0; i < 3; i++) {
      const dot = document.createElement('div');
      dot.className = 'typing-dot';
      typingContainer.appendChild(dot);
    }
    
    bubble.appendChild(typingContainer);
    indicatorDiv.appendChild(bubble);
    this.messagesArea.appendChild(indicatorDiv);
    
    this.typingIndicator = indicatorDiv;
    this.scrollToBottom();
  }

  removeTypingIndicator() {
    if (this.typingIndicator) {
      this.typingIndicator.remove();
      this.typingIndicator = null;
    }
  }

  scrollToBottom() {
    this.messagesArea.scrollTop = this.messagesArea.scrollHeight;
  }
}

// Instantiate on load
window.addEventListener('DOMContentLoaded', () => {
  new ChatWidget();
});
